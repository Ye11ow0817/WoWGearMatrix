const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
module.exports=async({win,storage,output})=>{
 win.webContents.setBackgroundThrottling(false);win.showInactive();
 const js=code=>win.webContents.executeJavaScript(code);
 const wait=async code=>{for(let i=0;i<1200;i++){if(await js(code))return;await new Promise(r=>setTimeout(r,50));}throw Error('UI timeout: '+code);};
 const settled=()=>wait(`!document.querySelector('#parse').disabled&&document.querySelector('#save-status').textContent==='已保存到本机'`);
 const character=()=>{const s=storage.load();return s.characters.find(c=>c.id===s.activeId);};
 const timings=[];
 const change=async(selector,value)=>{const start=performance.now();await js(`{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));}`);await settled();};
 const changeState=async value=>{const start=performance.now();await js(value==='none'?`document.querySelector('[data-profile-state]:checked').click()`:`document.querySelector('[data-profile-state="${value}"]').click()`);await settled();timings.push({value,ms:Math.round(performance.now()-start)});};
 await wait(`!document.querySelector('#app').hidden`);await settled();
 const sample=fs.readFileSync(path.join(__dirname,'engine/sample.simc'),'utf8');
 await js(`{const e=document.querySelector('#input');e.value=${JSON.stringify(sample)};e.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('#parse').click();}`);await settled();
 assert.equal(character().activeCharacterState,'battle_stance');
 assert.equal(await js(`document.querySelector('#profile-state')`),null);
 assert.equal(await js(`document.querySelector('#profile-state-note')`),null);
 assert.equal(await js(`document.querySelector('#profile-traits').textContent.includes('当前状态')`),false);
 assert.equal(await js(`document.querySelector('[data-trait="112224"]').closest('label').textContent.includes('狂野打击')`),true);
 assert.equal(await js(`document.querySelector('[data-trait="112224"]').closest('label').textContent.includes('+2%急速')`),true);
 assert.equal(character().basePercents.crit,10);
 const items=JSON.stringify(character().items);
 await changeState('defensive_stance');
 assert.equal(character().basePercents.crit,7);
 assert.equal(JSON.stringify(character().items),items);
 await js(`document.querySelector('#parse').click()`);await settled();
 assert.equal(character().characterState,'defensive_stance','reimport keeps explicit stance');
 assert.equal(character().basePercents.crit,7);
 const reimportedItems=JSON.stringify(character().items);
 await changeState('battle_stance');
 assert.equal(character().basePercents.crit,10);
 await changeState('defensive_stance');await changeState('battle_stance');
 await js(`document.querySelector('[data-trait="112235"]').click()`);await settled();
 assert.equal(character().activeCharacterState,'battle_stance');assert.equal(character().basePercents.crit,10);
 assert.equal(character().baseStats.stamina,4600);
 await change('#profile-race','goblin');assert.equal(character().basePercents.haste,3.02);
 await change('#profile-race','human');assert.equal(character().basePercents.haste,2);
 await change('#profile-race','night_elf');assert.equal(character().basePercents.haste,3.02);
 assert.equal(JSON.stringify(character().items),reimportedItems);
 await win.reload();await wait(`!document.querySelector('#app').hidden`);await settled();
 assert.equal(await js(`document.querySelector('[data-profile-state]:checked').dataset.profileState`),'battle_stance');
 assert.equal(await js(`document.querySelector('#base-percent-crit').value`),'10');
 win.showInactive();await js(`document.querySelector('#profile-traits').scrollIntoView({block:'center'});new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
 fs.writeFileSync(path.join(output,'warrior-state.png'),(await win.webContents.capturePage()).toPNG());
 await change('#profile-class','druid');await change('#profile-spec','guardian');
 assert.equal(character().activeCharacterState,'bear_form');
 const bear=character().baseStats.stamina;
 await changeState('none');assert(character().baseStats.stamina<bear);
 await changeState('bear_form');assert.equal(character().baseStats.stamina,bear);
 const vigor=await js(`document.querySelector('[data-trait="123793"]')!==null`);
 assert.equal(vigor,false,'temporary-only talent must not be offered as a fixed attribute');
 await js(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
 fs.writeFileSync(path.join(output,'druid-state.png'),(await win.webContents.capturePage()).toPNG());
 fs.writeFileSync(path.join(output,'state-ui-result.json'),JSON.stringify({passed:true,warriorCrit:10,bearStamina:bear,state:character().activeCharacterState,timings},null,2));
};
