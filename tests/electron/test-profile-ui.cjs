const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
module.exports=async({win,storage,output})=>{
  win.webContents.setBackgroundThrottling(false);
  const js=code=>win.webContents.executeJavaScript(code);
  const wait=async code=>{for(let n=0;n<1500;n++){if(await js(code))return;await new Promise(r=>setTimeout(r,40));}throw Error('UI wait failed: '+code);};
  // The save label can still show the previous save while SimC is running.
  const saved=()=>wait(`!importingId&&pending===0&&document.querySelector('#save-status').textContent==='已保存到本机'`);
  const change=async(selector,value)=>{await js(`{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));}`);await saved();};
  const character=()=>storage.load().characters[0];
  await wait(`document.querySelector('#app')&&!document.querySelector('#app').hidden`);await saved();
  if(process.env.SIMC_TEST_RESTORE==='1'){
    assert.equal(character().baseStats.stamina,5100);
    assert.equal(character().attributeContext.class,'shaman');
    assert.equal(character().attributeContext.spec,'elemental');
    fs.writeFileSync(path.join(output,'profile-restart-test.txt'),'PASS: displayed and raw stats plus profile choices persisted.');return;
  }
  assert.equal(await js(`document.querySelector('#profile-level')`),null);
  assert.equal(await js(`document.querySelector('#profile-calculate')`),null);
  assert.equal(character().baseStats.main,null);
  assert.equal(character().attributeContext.level,90);
  assert(await js(`!!document.querySelector('[data-trait="112235"]')`));
  assert(await js(`document.querySelector('[data-trait="112233"]').closest('label').textContent.includes('护甲10%的力量')`));
  assert(await js(`document.querySelector('[data-trait="112235"]').closest('label').textContent.includes('+10%耐力、+10%护甲')`));
  await change('#profile-class','shaman');await change('#profile-spec','elemental');
  const seer=character().traits.find(t=>t.id===136561);
  assert(seer);assert.equal(seer.multiplier.main,1.03);
  assert(await js(`document.querySelector('[data-trait="136561"]').closest('label').textContent.includes('+3%智力')`));
  assert(!await js(`document.querySelector('[data-trait="136561"]').closest('label').textContent.includes('+18智力')`));
  assert.equal(character().baseStats.main,620);
  const sample=fs.readFileSync(path.join(__dirname,'../fixtures/sample.simc'),'utf8');
  await js(`{const e=document.querySelector('#input');e.value=${JSON.stringify(sample)};e.dispatchEvent(new Event('input',{bubbles:true}));}`);
  await js(`document.querySelector('#parse').click()`);await wait(`!document.querySelector('#parse').disabled`);await saved();
  assert.equal(character().baseStats.main,618);assert.equal(character().baseStats.stamina,5060);
  await js(`document.querySelector('[data-trait="112235"]').click()`);await saved();
  assert.equal(character().baseStats.stamina,4600);
  assert.equal(character().traits.find(t=>t.id===112235).enabled,false);
  await change('#profile-race','orc');await change('#profile-class','shaman');await change('#profile-spec','elemental');
  assert.equal(character().attributeContext.class,'shaman');
  assert.equal(character().attributeContext.spec,'elemental');
  assert(character().traits.some(t=>t.id===136561));
  await js(`{const e=document.querySelector('#base-stamina');e.value='5100';e.dispatchEvent(new Event('input',{bubbles:true}));}`);await saved();
  assert.equal(character().baseStats.stamina,5100);
  assert(Math.abs(character().rawBaseStats.stamina-(5100-character().attributeOffset.stamina)/character().attributeFactors.stamina)<0.001);
  await js(`document.querySelector('[data-trait="136561"]').click()`);await saved();
  assert.equal(character().baseStats.stamina,5100);
  assert.equal(character().traits.find(t=>t.id===136561).enabled,true);
  assert.equal(character().attributeFactors.main,1.03);
  await js(`document.querySelector('#import-section').scrollIntoView({block:'start'})`);
  await js(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
  fs.writeFileSync(path.join(output,'profile-preview.png'),(await win.webContents.capturePage()).toPNG());
  fs.writeFileSync(path.join(output,'profile-ui-test.txt'),'PASS: async profile changes, imported talent recalculation, percent talent and inverse editing.');
};
