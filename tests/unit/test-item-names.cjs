const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{spawnSync}=require('node:child_process');
const M=require('../../src/shared/model.js'),metadata=require('../../data/item-names.source.json'),dictionary=require('../../data/item-names.json');
const raw=fs.readFileSync(path.join(__dirname,'../../data/item-names.json'));
assert.equal(crypto.createHash('sha256').update(raw).digest('hex'),metadata.sha256);
assert.equal(Object.keys(dictionary.byId).length,metadata.uniqueItemIds);
const item=(itemId,label,databaseName)=>M.parseReport(`Character: Names | warrior/arms | level=90\n[1] equipped / head / ${label}\nid=${itemId} | ${databaseName} | ilevel=300\nbase_for_spec: strength=10\ngear_flags: sockets=0, set_id=0, embellishment=0\n`).items[0];
assert.equal(item(271456,'Original exported name','Database English').name,'翡翠督军的淬火战角');
assert.equal(item(271456,'字符串中的另一中文名','Database English').name,'翡翠督军的淬火战角');
assert.equal(item(271456,'','Database English').name,'翡翠督军的淬火战角');
assert.equal(item(5549,'原字符串名称','Fast Test Dagger').name,'原字符串名称');
assert.equal(item(999999999,'Original exported name','Database English').name,'Original exported name');
assert.equal(item(999999999,'  ','Database English').name,'Database English');
const input='warrior="Names"\nlevel=90\nrace=human\nspec=arms\nhead=original_export_token,id=271456\nmain_hand=original_weapon_token,id=5549\nmain_hand=,id=5549\n';
const run=spawnSync(process.execPath,[path.join(__dirname,'../../engine/run.cjs'),'-'],{input,encoding:'utf8',timeout:30000,maxBuffer:8*1024*1024});
if(run.error)throw run.error;
const result=M.parseReport(run.stdout);
assert.equal(result.failed,0,run.stdout);
assert.equal(result.items.length,3,run.stdout);
assert.deepEqual(result.items.map(i=>i.name),['翡翠督军的淬火战角','original_weapon_token','Fast Test Dagger']);
assert.match(run.stdout,/equipped \/ head \/ original_export_token/);
assert.match(run.stdout,new RegExp('^Source: '+require('../../engine/manifest.json').simcCommit+'$','m'));
console.log('PASS: original dictionary integrity, Chinese > exported name > database English, untranslated/missing ID fallback, and real WASM name tokens.');
